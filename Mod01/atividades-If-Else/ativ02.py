idade = int(input('Digite a idade do seu carro: '))

# Essa condicional verifica se a idade do carro é menor ou igual a 3 anos
# Mostra que o carro é novo
if idade <= 3: 
    print('Seu carro é novo!')
# Verifica se a idade do carro é maior que 3 anos.
# Mostra que o carro é velho.   
if idade > 3:
    print('Seu carro é velho!')